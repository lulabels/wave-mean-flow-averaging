def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def command_for(figure: int) -> list[str]:
    python = sys.executable
    script_dir = ROOT / "figures"
    if 1 <= figure <= 6:
        return [python, str(script_dir / f"figure{figure}.py")]
    if figure in (7, 8):
        return [python, str(script_dir / "figures7_8.py"), "--only", str(figure)]
    if figure == 9:
        return [python, str(script_dir / "figure9.py")]
    raise ValueError(f"Figure {figure} is not code-generated by this bundle")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--figures",
        type=int,
        nargs="+",
        choices=range(1, 10),
        default=None,
        help="paper figures to reproduce (default: 2 through 8 plus graphical abstract)",
    )
    parser.add_argument(
        "--include-figure9",
        action="store_true",
        help="append Figure 9 to the default set after running generate_data/download_baker_data.py",
    )
    parser.add_argument(
        "--verify-hashes",
        action="store_true",
        help="require byte-identical submitted PNGs (needs the pinned environment and compatible fonts)",
    )
    parser.add_argument(
        "--graphical-abstract", action="store_true",
        help="render the graphical abstract alone, or alongside explicitly selected figures",
    )
    args = parser.parse_args()
    selected = args.figures if args.figures is not None else (
        [] if args.graphical_abstract else list(range(2, 9)))
    figures = list(dict.fromkeys(selected + ([9] if args.include_figure9 else [])))
    do_graphical_abstract = args.graphical_abstract or args.figures is None

    (ROOT / "outputs").mkdir(parents=True, exist_ok=True)
    (ROOT / "work" / "matplotlib").mkdir(parents=True, exist_ok=True)
    for figure in figures:
        print(f"reproducing Figure {figure}", flush=True)
        subprocess.run(command_for(figure), check=True, cwd=ROOT)

    if do_graphical_abstract:
        print("reproducing graphical abstract", flush=True)
        subprocess.run([
            sys.executable, str(ROOT / "figures/graphical_abstract.py"), "--verify",
        ], check=True, cwd=ROOT)

    failures = []
    for figure in figures:
        output = ROOT / "outputs" / f"fig{figure}.png"
        actual = sha256(output)
        status = "submitted-byte-match" if actual == EXPECTED[figure] else "portable-render-difference"
        print(f"Figure {figure}: {status} ({actual})")
        if args.verify_hashes and actual != EXPECTED[figure]:
            failures.append(figure)
    if do_graphical_abstract:
        output = ROOT / "outputs/graphical_abstract/graphical_abstract.png"
        actual = sha256(output)
        status = "reference-byte-match" if actual == EXPECTED_GRAPHICAL_ABSTRACT else "portable-render-difference"
        print(f"Graphical abstract: {status} ({actual})")
        if args.verify_hashes and actual != EXPECTED_GRAPHICAL_ABSTRACT:
            failures.append("graphical abstract")
    if failures:
        raise SystemExit(f"byte-hash mismatch for figures: {', '.join(map(str, failures))}")


if __name__ == "__main__":
    main()
